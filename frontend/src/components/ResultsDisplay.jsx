import React, { useState } from 'react';
import { ShieldCheckIcon, AlertTriangleIcon, LayersIcon, EyeIcon } from './Icons';

export default function ResultsDisplay({ result, status }) {
  const [showOriginal, setShowOriginal] = useState(false);

  if (!result && status !== 'analyzing') {
    return (
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-8 text-center text-slate-500 text-xs">
        <p>Awaiting query. Upload a satellite image and click "Analyze image" to view the AI answer and grounded visual evidence.</p>
      </div>
    );
  }

  if (status === 'analyzing') {
    return (
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-8 text-center flex flex-col items-center justify-center gap-3">
        <div className="w-8 h-8 border-2 border-blue-500 border-t-transparent rounded-full animate-spin"></div>
        <p className="text-sm font-medium text-slate-200">
          Analyzing satellite imagery...
        </p>
        <p className="text-xs text-slate-400">
          Extracting visual features and searching for grounding evidence
        </p>
      </div>
    );
  }

  const {
    answer,
    detections = [],
    evidence_image,
    abstained = false,
    evidence_found = false,
  } = result;

  return (
    <div className="flex flex-col gap-6">
      {/* 1. ABSTENTION STATE (when result.abstained === true) */}
      {abstained ? (
        <div className="bg-amber-950/30 border border-amber-600/50 rounded-xl p-5 shadow-sm">
          <div className="flex items-start gap-3.5">
            <AlertTriangleIcon size={24} className="text-amber-400 shrink-0 mt-0.5" />
            <div className="flex-1">
              <h3 className="text-sm font-bold text-amber-300 uppercase tracking-wide">
                Unable to answer reliably
              </h3>
              <p className="text-sm text-amber-200/90 mt-1.5 leading-relaxed font-medium">
                The available visual evidence is insufficient to support a reliable answer.
              </p>
              {answer && (
                <div className="mt-3 bg-amber-950/50 border border-amber-800/50 rounded-lg p-3 text-xs text-amber-200/80 leading-relaxed">
                  <span className="font-semibold block mb-0.5 text-amber-300">Model Explanation:</span>
                  {answer}
                </div>
              )}
            </div>
          </div>
        </div>
      ) : (
        /* 2. SUCCESSFUL ANSWER STATE (when result.abstained === false) */
        <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-sm flex flex-col gap-3">
          <div className="flex items-center justify-between">
            <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400">
              AI Answer
            </h3>
            <span className="flex items-center gap-1.5 text-xs text-emerald-400 font-medium">
              <ShieldCheckIcon size={14} />
              Grounded Answer
            </span>
          </div>

          <div className="bg-[#070b14] border border-slate-800 rounded-lg p-4 text-sm text-slate-100 leading-relaxed whitespace-pre-wrap font-sans">
            {answer}
          </div>
        </div>
      )}

      {/* 3. VISUAL EVIDENCE SECTION */}
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-sm flex flex-col gap-4">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <LayersIcon size={16} className="text-blue-400" />
            <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-300">
              Visual Evidence
            </h3>
          </div>
          <span className="text-xs font-mono px-2.5 py-0.5 rounded-full bg-slate-800 text-slate-300 border border-slate-700">
            {detections.length === 1
              ? '1 region detected'
              : `${detections.length} regions detected`}
          </span>
        </div>

        {/* Prominent Evidence Image with backend bounding boxes */}
        {evidence_image ? (
          <div className="flex flex-col gap-2">
            <div className="relative bg-[#070b14] border border-slate-800 rounded-lg overflow-hidden flex items-center justify-center p-2">
              <img
                src={`data:image/png;base64,${evidence_image}`}
                alt="Visual Evidence with Grounded Bounding Boxes"
                className="max-h-[460px] w-auto max-w-full rounded object-contain shadow-md"
              />
            </div>
            <p className="text-[11px] text-slate-400 text-center">
              Visual evidence with localized bounding boxes generated by the grounding backend.
            </p>
          </div>
        ) : (
          <div className="p-6 bg-[#070b14] border border-slate-800/80 rounded-lg text-center text-xs text-slate-500">
            No evidence image returned for this query.
          </div>
        )}

        {/* Detections List: Labels, Scores, Coordinates */}
        {detections.length > 0 && (
          <div className="flex flex-col gap-2 pt-2 border-t border-slate-800">
            <span className="text-xs font-medium text-slate-400">
              Detected Regions ({detections.length}):
            </span>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
              {detections.map((item, idx) => (
                <div
                  key={idx}
                  className="bg-[#070b14] border border-slate-800 rounded-lg p-3 text-xs flex flex-col gap-1.5"
                >
                  <div className="flex items-center justify-between">
                    <span className="font-semibold text-slate-200 capitalize">
                      {item.label} #{idx + 1}
                    </span>
                    {item.score !== undefined && item.score !== null && (
                      <span className="font-mono text-xs text-blue-400 font-medium">
                        Score: {item.score}
                      </span>
                    )}
                  </div>
                  {item.box && (
                    <div className="text-[11px] font-mono text-slate-400 bg-slate-800/60 px-2 py-1 rounded">
                      Box: [{item.box.join(', ')}]
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
